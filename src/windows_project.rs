use serde_json::Value;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const CS_FILES: &[(&str, &str)] = &[
    ("DragonNative.cs", include_str!("../templates/windows/cs/DragonNative.cs")),
    ("DragonPlugin.cs", include_str!("../templates/windows/cs/DragonPlugin.cs")),
    ("Json.cs", include_str!("../templates/windows/cs/Json.cs")),
    ("DragonPlatform.cs", include_str!("../templates/windows/cs/DragonPlatform.cs")),
    ("DragonHost.cs", include_str!("../templates/windows/cs/DragonHost.cs")),
    ("Panels.cs", include_str!("../templates/windows/cs/Panels.cs")),
    ("Theme.cs", include_str!("../templates/windows/cs/Theme.cs")),
    ("Renderer.cs", include_str!("../templates/windows/cs/Renderer.cs")),
    ("Controls.cs", include_str!("../templates/windows/cs/Controls.cs")),
    ("App.cs", include_str!("../templates/windows/cs/App.cs")),
];
const CSPROJ: &str = include_str!("../templates/windows/App.csproj.template");
const MANIFEST: &str = include_str!("../templates/windows/app.manifest.template");
const ICON_FONT: &[u8] = include_bytes!("../framework/fonts/MaterialIcons-Regular.ttf");

struct WinApp {
    name: String,
    title: String,
    main: String,
    dir: PathBuf,
    width: i64,
    height: i64,
}

fn write(path: &Path, bytes: &[u8]) -> Result<(), String> {
    if let Some(p) = path.parent() { fs::create_dir_all(p).map_err(|e| format!("couldn't create {}: {}", p.display(), e))?; }
    fs::write(path, bytes).map_err(|e| format!("couldn't write {}: {}", path.display(), e))
}

fn assembly_name(name: &str) -> String {
    let s: String = name.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '_').collect();
    if s.is_empty() || s.chars().next().unwrap().is_ascii_digit() { format!("App{}", s) } else { s }
}

fn read_app() -> Result<WinApp, String> {
    let data = fs::read_to_string("package.json").map_err(|_| "'package.json' not found -- run this inside a Dragon project".to_string())?;
    let j: Value = serde_json::from_str(&data).map_err(|e| format!("'package.json' is invalid JSON: {}", e))?;
    let name = j.get("name").and_then(|v| v.as_str()).unwrap_or("app").to_string();
    let main = j.get("main").and_then(|v| v.as_str()).unwrap_or("lib/main.dgn").to_string();
    let win = j.get("windows");
    let title = win.and_then(|w| w.get("title")).and_then(|v| v.as_str()).unwrap_or(&name).to_string();
    let dir = PathBuf::from(win.and_then(|w| w.get("dir")).and_then(|v| v.as_str()).unwrap_or("windows"));
    let width = win.and_then(|w| w.get("width")).and_then(|v| v.as_i64()).unwrap_or(420);
    let height = win.and_then(|w| w.get("height")).and_then(|v| v.as_i64()).unwrap_or(800);
    Ok(WinApp { name, title, main, dir, width, height })
}

fn cs_string(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c { '"' => o.push_str("\\\""), '\\' => o.push_str("\\\\"), '\n' => o.push_str("\\n"), _ => o.push(c) }
    }
    o.push('"');
    o
}

fn copy_tree(src: &Path, dst: &Path) -> Result<(), String> {
    fs::create_dir_all(dst).map_err(|e| e.to_string())?;
    for e in fs::read_dir(src).map_err(|e| e.to_string())?.flatten() {
        let p = e.path();
        let t = dst.join(e.file_name());
        if p.is_dir() { copy_tree(&p, &t)?; } else { fs::copy(&p, &t).map_err(|e| e.to_string())?; }
    }
    Ok(())
}

pub fn windows_init() -> Result<(), String> {
    let app = read_app()?;
    let src = app.dir.join("Sources");
    let rt = src.join("DragonRuntime");
    let _ = fs::remove_dir_all(&rt);
    for (n, t) in CS_FILES { write(&rt.join(n), t.as_bytes())?; }
    write(&app.dir.join("Resources/Fonts/MaterialIcons-Regular.ttf"), ICON_FONT)?;

    let assets_out = app.dir.join("Resources/assets");
    let _ = fs::remove_dir_all(&assets_out);
    fs::create_dir_all(&assets_out).map_err(|e| e.to_string())?;
    if Path::new("assets").is_dir() { copy_tree(Path::new("assets"), &assets_out)?; }

    let used = crate::packages::used_packages(&crate::packages::app_root_of(Path::new(&app.main)));
    let plug_dir = src.join("Plugins");
    let _ = fs::remove_dir_all(&plug_dir);
    let mut plugins: Vec<String> = Vec::new();
    let mut nuget: Vec<String> = Vec::new();
    let mut with_native: Vec<String> = Vec::new();
    for p in &used {
        let cs = p.root.join("native/windows/cs");
        if cs.is_dir() { copy_tree(&cs, &plug_dir.join(&p.name))?; with_native.push(p.name.clone()); }
        if let Some(c) = p.windows_str("plugin") { plugins.push(c); }
        for n in p.windows_list("nuget") { if !nuget.contains(&n) { nuget.push(n); } }
    }
    let list = plugins.iter().map(|c| format!("                new {}(ctx)", c)).collect::<Vec<_>>().join(",\n");
    let reg = format!(
        "// Generated by `dragon windows init`. Do not edit.\nusing System.Collections.Generic;\n\nnamespace DragonRuntime\n{{\n    internal static class DragonAppInfo\n    {{\n        public const string Title = {};\n        public const int Width = {};\n        public const int Height = {};\n    }}\n\n    internal static class DragonPlugins\n    {{\n        public static List<IDragonPlugin> Create(PluginContext ctx)\n        {{\n            return new List<IDragonPlugin>\n            {{\n{}\n            }};\n        }}\n    }}\n}}\n",
        cs_string(&app.title), app.width, app.height, list);
    write(&src.join("DragonPlugins.cs"), reg.as_bytes())?;

    let extra: String = nuget.iter().filter_map(|n| {
        let (id, ver) = n.split_once(':')?;
        Some(format!("    <PackageReference Include=\"{}\" Version=\"{}\" />\n", id, ver))
    }).collect();
    let extra = if extra.is_empty() { String::new() } else { format!("  </ItemGroup>\n  <ItemGroup>\n{}", extra.trim_end_matches('\n')) };
    let asm = assembly_name(&app.name);
    let proj = CSPROJ.replace("__ASSEMBLY__", &asm).replace("__EXTRA__", &extra);
    write(&app.dir.join(format!("{}.csproj", asm)), proj.as_bytes())?;
    write(&app.dir.join("app.manifest"), MANIFEST.as_bytes())?;
    write(&app.dir.join(".gitignore"), b"Native/\nbin/\nobj/\n")?;
    println!("Windows project written to {}/  (see docs/WINDOWS.md)", app.dir.display());
    if !used.is_empty() {
        println!("  packages: {}", used.iter().map(|p| p.name.as_str()).collect::<Vec<_>>().join(", "));
    }
    let missing: Vec<&str> = used.iter().filter(|p| p.manifest.get("windows").is_none()).map(|p| p.name.as_str()).collect();
    if !missing.is_empty() {
        println!("  note: no Windows implementation in: {} (their native calls will report 'unsupported')", missing.join(", "));
    }
    Ok(())
}

pub fn windows_build(release: bool) -> Result<PathBuf, String> {
    use crate::codegen_c::{compile_app, CrossBuildOptions, CrossTarget};
    windows_init()?;
    let app = read_app()?;
    let native = app.dir.join("Native");
    fs::create_dir_all(&native).map_err(|e| e.to_string())?;
    let opts = CrossBuildOptions {
        targets: vec![CrossTarget::WindowsX64], android_api: 24, ios_min_version: "16.0".into(), make_xcframework: false, jni_package: None, jni_class: None,
    };
    println!("Compiling {} to a native Windows DLL...", app.main);
    compile_app(Path::new(&app.main), &native.join("dragon_lib"), false, &opts, false)?;
    let dll = native.join("dragon_lib.dll");
    if !dll.is_file() { return Err(format!("expected {} after compiling, but it is missing", dll.display())); }
    if !cfg!(target_os = "windows") && Command::new("dotnet").arg("--version").output().map(|o| !o.status.success()).unwrap_or(true) {
        println!("The native library is ready in {}. Run `dragon windows build` on Windows (with the .NET 8 SDK) to produce the .exe.", native.display());
        return Ok(dll);
    }
    let asm = assembly_name(&app.name);
    let cfg = if release { "Release" } else { "Debug" };
    let st = Command::new("dotnet")
        .current_dir(&app.dir)
        .args(["build", &format!("{}.csproj", asm), "-c", cfg, "-nologo"])
        .status().map_err(|e| format!("dotnet: {}", e))?;
    if !st.success() { return Err("dotnet build failed (see output above)".into()); }
    let out = app.dir.join("bin").join(cfg).join("net8.0-windows").join("win-x64");
    println!("Built {}", out.join(format!("{}.exe", asm)).display());
    Ok(out.join(format!("{}.exe", asm)))
}

pub fn windows_run(release: bool) -> Result<(), String> {
    if !cfg!(target_os = "windows") {
        windows_build(release)?;
        return Err("Running a Windows app needs Windows. The project is built; run `dragon run --platform windows` there.".into());
    }
    let exe = windows_build(release)?;
    Command::new(&exe).status().map_err(|e| format!("couldn't start {}: {}", exe.display(), e))?;
    Ok(())
}
