use serde_json::{json, Value};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const SW_NATIVE: &str = include_str!("../templates/ios/swift/DragonNative.swift");
const SW_PLUGIN: &str = include_str!("../templates/ios/swift/DragonPlugin.swift");
const SW_PLATFORM: &str = include_str!("../templates/ios/swift/DragonPlatform.swift");
const SW_HOST: &str = include_str!("../templates/ios/swift/DragonHost.swift");
const SW_APP: &str = include_str!("../templates/ios/swift/DragonApp.swift");
const SW_RENDERER: &str = include_str!("../templates/ios/swift/DragonRenderer.swift");
const BRIDGING: &str = include_str!("../templates/ios/Dragon-Bridging-Header.h");
const ICON_FONT: &[u8] = include_bytes!("../framework/fonts/MaterialIcons-Regular.ttf");

const LIB: &str = "dragon_lib";

struct IosApp {
    name: String,
    bundle_id: String,
    main: String,
    ios_dir: PathBuf,
    min_ios: String,
    info_plist: serde_json::Map<String, Value>,
}

fn write(path: &Path, bytes: &[u8]) -> Result<(), String> {
    if let Some(p) = path.parent() { fs::create_dir_all(p).map_err(|e| format!("couldn't create {}: {}", p.display(), e))?; }
    fs::write(path, bytes).map_err(|e| format!("couldn't write {}: {}", path.display(), e))
}

fn product_name(name: &str) -> String {
    let s: String = name.chars().filter(|c| c.is_ascii_alphanumeric()).collect();
    if s.is_empty() { "DragonApp".into() } else { s }
}

fn read_app() -> Result<IosApp, String> {
    let data = fs::read_to_string("package.json").map_err(|_| "'package.json' not found -- run this inside a Dragon project".to_string())?;
    let j: Value = serde_json::from_str(&data).map_err(|e| format!("'package.json' is invalid JSON: {}", e))?;
    let name = j.get("name").and_then(|v| v.as_str()).unwrap_or("app").to_string();
    let main = j.get("main").and_then(|v| v.as_str()).unwrap_or("lib/main.dgn").to_string();
    let ios = j.get("ios");
    let bundle_id = ios.and_then(|i| i.get("bundleId")).and_then(|v| v.as_str())
        .or_else(|| j.get("package").and_then(|v| v.as_str()))
        .map(|s| s.to_string())
        .unwrap_or_else(|| format!("com.example.{}", product_name(&name).to_lowercase()));
    let ios_dir = PathBuf::from(ios.and_then(|i| i.get("dir")).and_then(|v| v.as_str()).unwrap_or("ios"));
    let min_ios = ios.and_then(|i| i.get("minVersion")).and_then(|v| v.as_str()).unwrap_or("16.0").to_string();
    let info_plist = ios.and_then(|i| i.get("infoPlist")).and_then(|v| v.as_object()).cloned().unwrap_or_default();
    Ok(IosApp { name, bundle_id, main, ios_dir, min_ios, info_plist })
}

pub fn ios_init() -> Result<(), String> {
    let app = read_app()?;
    let src = app.ios_dir.join("Sources");
    let rt = src.join("DragonRuntime");
    for (n, t) in [("DragonNative.swift", SW_NATIVE), ("DragonPlugin.swift", SW_PLUGIN), ("DragonPlatform.swift", SW_PLATFORM),
                   ("DragonHost.swift", SW_HOST), ("DragonApp.swift", SW_APP), ("DragonRenderer.swift", SW_RENDERER)] {
        write(&rt.join(n), t.as_bytes())?;
    }
    write(&src.join("Dragon-Bridging-Header.h"), BRIDGING.as_bytes())?;
    write(&app.ios_dir.join("Resources/MaterialIcons-Regular.ttf"), ICON_FONT)?;

    let assets_out = app.ios_dir.join("Resources/assets");
    let _ = fs::remove_dir_all(&assets_out);
    fs::create_dir_all(&assets_out).map_err(|e| e.to_string())?;
    if Path::new("assets").is_dir() { copy_tree(Path::new("assets"), &assets_out)?; }

    let used = crate::packages::used_packages(&crate::packages::app_root_of(Path::new(&app.main)));
    let plug_dir = src.join("Plugins");
    let _ = fs::remove_dir_all(&plug_dir);
    let mut plugins: Vec<String> = Vec::new();
    let mut info = app.info_plist.clone();
    for p in &used {
        let sw = p.root.join("native/ios/swift");
        if sw.is_dir() { copy_tree(&sw, &plug_dir.join(&p.name))?; }
        if let Some(c) = p.ios_str("plugin") { plugins.push(c); }
        if let Some(m) = p.manifest.get("ios").and_then(|i| i.get("infoPlist")).and_then(|v| v.as_object()) {
            for (k, v) in m { info.entry(k.clone()).or_insert(v.clone()); }
        }
    }
    let list = plugins.iter().map(|c| format!("        {}(context: ctx)", c)).collect::<Vec<_>>().join(",\n");
    let reg = format!("// Generated by `dragon ios init` from the packages this app imports. Do not edit.\nenum DragonPlugins {{\n    static func create(_ ctx: PluginContext) -> [DragonPlugin] {{\n        [\n{}\n        ]\n    }}\n}}\n",
        if plugins.is_empty() { String::new() } else { list });
    write(&src.join("DragonPlugins.swift"), reg.as_bytes())?;

    let product = product_name(&app.name);
    let mut props = serde_json::Map::new();
    props.insert("CFBundleDisplayName".into(), json!(app.name));
    props.insert("UILaunchScreen".into(), json!({}));
    props.insert("UISupportedInterfaceOrientations".into(), json!(["UIInterfaceOrientationPortrait", "UIInterfaceOrientationLandscapeLeft", "UIInterfaceOrientationLandscapeRight"]));
    for (k, v) in info { props.insert(k, v); }
    let spec = json!({
        "name": product,
        "options": { "deploymentTarget": { "iOS": app.min_ios } },
        "targets": {
            product.clone(): {
                "type": "application",
                "platform": "iOS",
                "sources": [
                    { "path": "Sources" },
                    { "path": "Resources/MaterialIcons-Regular.ttf" },
                    { "path": "Resources/assets", "type": "folder" }
                ],
                "dependencies": [ { "framework": format!("Native/{}.xcframework", LIB), "embed": false } ],
                "settings": { "base": {
                    "PRODUCT_BUNDLE_IDENTIFIER": app.bundle_id,
                    "SWIFT_OBJC_BRIDGING_HEADER": "Sources/Dragon-Bridging-Header.h",
                    "SWIFT_VERSION": "5.9",
                    "GENERATE_INFOPLIST_FILE": "YES",
                    "TARGETED_DEVICE_FAMILY": "1,2"
                } },
                "info": { "path": "Info.plist", "properties": Value::Object(props) }
            }
        }
    });
    write(&app.ios_dir.join("project.yml"), serde_json::to_string_pretty(&spec).unwrap().as_bytes())?;
    write(&app.ios_dir.join(".gitignore"), b"Native/\n*.xcodeproj\nInfo.plist\nbuild/\n")?;
    println!("iOS project inputs written to {}/  (UNTESTED on real Xcode, see docs/IOS.md)", app.ios_dir.display());
    if !used.is_empty() {
        println!("  packages: {}", used.iter().map(|p| p.name.as_str()).collect::<Vec<_>>().join(", "));
    }
    Ok(())
}

fn copy_tree(src: &Path, dst: &Path) -> Result<(), String> {
    fs::create_dir_all(dst).map_err(|e| e.to_string())?;
    for e in fs::read_dir(src).map_err(|e| e.to_string())?.flatten() {
        let p = e.path();
        let t = dst.join(e.file_name());
        if p.is_dir() { copy_tree(&p, &t)?; } else { fs::copy(&p, &t).map_err(|e| e.to_string())?; }
    }
    Ok(())
}

pub fn ios_build(simulator_only: bool) -> Result<(), String> {
    use crate::codegen_c::{compile_app, CrossBuildOptions, CrossTarget};
    ios_init()?;
    let app = read_app()?;
    if !cfg!(target_os = "macos") {
        return Err(format!("Building for iOS needs macOS with Xcode. The project inputs are in {}/ -- run `dragon ios build` on a Mac.", app.ios_dir.display()));
    }
    let mut targets = vec![CrossTarget::IosArm64Simulator, CrossTarget::IosX86_64Simulator];
    if !simulator_only { targets.insert(0, CrossTarget::IosArm64); }
    let opts = CrossBuildOptions {
        targets, android_api: 24, ios_min_version: app.min_ios.clone(), make_xcframework: true, jni_package: None, jni_class: None,
    };
    let native = app.ios_dir.join("Native");
    fs::create_dir_all(&native).map_err(|e| e.to_string())?;
    println!("Compiling {} to native code for iOS...", app.main);
    compile_app(Path::new(&app.main), &native.join(LIB), false, &opts, false)?;

    let which = |t: &str| Command::new("which").arg(t).output().map(|o| o.status.success()).unwrap_or(false);
    if !which("xcodegen") {
        return Err(format!("XcodeGen not found (brew install xcodegen). Native library is ready in {}/Native; run `xcodegen` in {}/ and open the project.", app.ios_dir.display(), app.ios_dir.display()));
    }
    let st = Command::new("xcodegen").current_dir(&app.ios_dir).status().map_err(|e| format!("xcodegen: {}", e))?;
    if !st.success() { return Err("xcodegen failed".into()); }
    let product = product_name(&app.name);
    let st = Command::new("xcodebuild")
        .current_dir(&app.ios_dir)
        .args(["-project", &format!("{}.xcodeproj", product), "-scheme", &product, "-sdk", "iphonesimulator", "-configuration", "Debug", "-derivedDataPath", "build", "build"])
        .status().map_err(|e| format!("xcodebuild: {}", e))?;
    if !st.success() { return Err("xcodebuild failed (see output above)".into()); }
    println!("Built {}. Open {}/{}.xcodeproj in Xcode to run on a device.", product, app.ios_dir.display(), product);
    Ok(())
}

pub fn ios_run() -> Result<(), String> {
    ios_build(true)?;
    let app = read_app()?;
    let product = product_name(&app.name);
    let bundle = app.ios_dir.join("build/Build/Products/Debug-iphonesimulator").join(format!("{}.app", product));
    if !bundle.exists() { return Err(format!("{} not found after the build", bundle.display())); }
    let _ = Command::new("xcrun").args(["simctl", "boot", "iPhone 15"]).status();
    let _ = Command::new("open").args(["-a", "Simulator"]).status();
    let st = Command::new("xcrun").args(["simctl", "install", "booted"]).arg(&bundle).status().map_err(|e| format!("xcrun: {}", e))?;
    if !st.success() { return Err("simctl install failed (is a simulator booted?)".into()); }
    let st = Command::new("xcrun").args(["simctl", "launch", "booted", &app.bundle_id]).status().map_err(|e| format!("xcrun: {}", e))?;
    if !st.success() { return Err("simctl launch failed".into()); }
    Ok(())
}
